CREATE TABLE customer (
    id BIGINT PRIMARY KEY,
    full_name VARCHAR(160) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE trusted_device (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer(id),
    device_id VARCHAR(160) NOT NULL,
    trusted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_customer_device UNIQUE(customer_id, device_id)
);

CREATE TABLE login_attempt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(100) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customer(id),
    device_id VARCHAR(160) NOT NULL,
    country_code VARCHAR(3) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    credential_valid BOOLEAN NOT NULL,
    outcome VARCHAR(20) NOT NULL,
    event_time TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE risk_decision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(100) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customer(id),
    score INTEGER NOT NULL,
    decision VARCHAR(20) NOT NULL,
    reason_codes VARCHAR(500) NOT NULL,
    step_up_status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Composite indexes are portable to H2 PostgreSQL mode and PostgreSQL.
CREATE INDEX idx_login_passed_customer_time
    ON login_attempt(customer_id, outcome, event_time DESC);
CREATE INDEX idx_login_failed_customer_time
    ON login_attempt(customer_id, outcome, event_time DESC);
CREATE INDEX idx_decision_created
    ON risk_decision(created_at DESC, id DESC);
CREATE INDEX idx_decision_customer_created
    ON risk_decision(customer_id, created_at DESC);
